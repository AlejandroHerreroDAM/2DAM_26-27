/*1. Retrieve the appointments of a particular patient, displaying the
appointment date and the patient's name: */

select a.patient_name as "patient's name", p.appointment_date as "appointment's date"
from appointments a
join patients p
    on a.patient_id = p.patient_name
where a.patient_name = "Pepe";


/*2. Retrieve the appointments of a specific patient, displaying the appointment
date, the patient's name, and the doctor's name:*/

select a.patient_name as "patient's name", p.appointment_date as "appointment's date", d.doctor_name as "doctor's name"
from appointments a
join patients p
    on a.patient_id = p.patient_name
join doctors d
    on p.doctor_id = d.doctor_name
where a.patient_name = "Pepe";


/*3. Retrieve the appointments of a particular patient, displaying the
appointment date, the patient's name, the doctor’s name, and the diagnosis
from their medical record (if available):*/

select a.patient_name as "patient's name", p.appointment_date as "appointment's date", d.doctor_name as "doctor's name", m.diagnosis
from appointments a
join patients p
    on a.patient_id = p.patient_id
join doctors d
    on p.doctor_id = d.doctor_name
join medical_records m
    on a.patient_id = m.patient_id and p.doctor_id = m.doctor_id
where a.patient_name = "Pepe";


/*4. Determine the number of medications prescribed in each medical record:*/

select prescription_id, count(prescription_id) as "Prescribed medications"
from prescribed_medications
group by prescription_id;


/*5. Identify the names of the two oldest patients based on their date of birth:*/

select patient_name, date_of_birth
from patients
order by date_of_birth
limit 2;


/*6. Find the name of the patient who has spent the most money in the system:*/

select p.patient_name, sum(pay.amount) as "total payment"
from patients p
join patient_payments pay
    on p.patient_id=pay.patient_id
group by p.patient_id
order by sum(pay.amount) desc
limit 1;


/*7. Retrieve the name of the doctor who has given the most prescriptions:*/

select d.doctor_name, count(pm.prescription_id) as "total prescriptions"
from doctors d
join medical_records mr
    on d.doctor_id=mr.doctor_id
join prescribed_medications pm
    on mr.record_id=pm.record_id
group by d.doctor_id
order by count(pm.prescription_id) desc
limit 1;


/*8. Calculate the total revenue generated by each doctor, along with the
number of appointments for each doctor, and sort the results by revenue:*/

select d.doctor_name, count(a.appointment_id) as "appointments by doctor" sum(pay.amount) as "revenue by doctor"
from doctors d
join appointments 
    on d.doctor_id=a.doctor_id
join medical_records mr
    on d.doctor_id=mr.doctor_id
join patient_payments pay
    on mr.patient_id=pay.patient_id
group by d.doctor_id
order by sum(pay.amount) desc;


/*9. Find the number of patients treated by each doctor and sort by the number
of patients:*/

select d.doctor_name, count(mr.patient_id) as "patient count"
from doctors d
join medical_records mr
    on d.doctor_id=mr.doctor_id
group by d.doctor_id
order by count(mr.patient_id);


/*10. Retrieve the total number of appointments scheduled per day:*/

select date(appointment_date), count(appointment_id) as "Appointments per day"
from appointments
group by appointment_date;
